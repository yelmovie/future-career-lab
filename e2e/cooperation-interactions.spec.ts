import { expect, test, type Page } from '@playwright/test';
import { createDefaultSave } from '../src/state/defaultSave';
const KEY = 'future-career-lab.save.v1';

async function seed(page: Page, legacy?: unknown) {
  const save = createDefaultSave();
  save.audio = { muted: true, bgmVolume: 0, sfxVolume: 0 };
  save.stageProgress.completedPages = [3, 4, 5, 6, 7, 8];
  save.artifacts.clip = { trust: 100, corrections: 0 };
  if (legacy) save.pageData.p9Alliance = legacy;
  await page.goto('/#/page/1');
  await page.evaluate(({ key, value }) => localStorage.setItem(key, JSON.stringify(value)), { key: KEY, value: save });
  await page.reload(); await page.goto('/#/page/9');
}
const read = (page: Page) => page.evaluate((key) => JSON.parse(localStorage.getItem(key) ?? '{}'), KEY);
async function mousePlant(page: Page, site: string) {
  const start = await page.getByRole('button', { name: '열매나무 묘목', exact: true }).boundingBox();
  const end = await page.locator(`[data-plant-site="${site}"]`).boundingBox();
  await page.mouse.move(start!.x + start!.width / 2, start!.y + start!.height / 2); await page.mouse.down();
  await page.mouse.move(end!.x + end!.width / 2, end!.y + end!.height / 2, { steps: 12 }); await page.mouse.up();
}

