test('tablet touch events support drag cancellation, tap alternatives, water marking and a slider', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 1024, height: 768 }, hasTouch: true });
  const page = await context.newPage(); await seed(page);
  await page.getByRole('button', { name: '함께 숲으로 가기' }).tap();
  await page.getByRole('button', { name: '나무가 베인 곳 도와주기', exact: true }).tap();
  const client = await context.newCDPSession(page);
  const touch = async (type: 'touchStart' | 'touchMove' | 'touchEnd' | 'touchCancel', x = 0, y = 0) => client.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' || type === 'touchCancel' ? [] : [{ x, y, id: 0, radiusX: 8, radiusY: 8, force: 1 }] });
  const start = await page.getByRole('button', { name: '열매나무 묘목', exact: true }).boundingBox();
  const end = await page.locator('[data-plant-site="left"]').boundingBox();
  await touch('touchStart', start!.x + start!.width / 2, start!.y + start!.height / 2);
  await touch('touchMove', end!.x + end!.width / 2, end!.y + end!.height / 2); await touch('touchCancel');
  await expect(page.locator('.coop-plant-site.is-planted')).toHaveCount(0);
  await touch('touchStart', start!.x + start!.width / 2, start!.y + start!.height / 2);
  await touch('touchMove', end!.x + end!.width / 2, end!.y + end!.height / 2); await touch('touchEnd');
  await expect(page.locator('.coop-plant-site.is-planted')).toHaveCount(1);
  await page.getByRole('button', { name: '열매나무 묘목', exact: true }).tap();
  await page.getByRole('button', { name: '2번 자리에 묘목 심기' }).tap();
  await expect(page.locator('.coop-plant-site.is-planted')).toHaveCount(2);
  await page.getByRole('button', { name: '함께 나무 돌보기' }).tap();
  await page.getByRole('button', { name: '다른 곳도 도와주기' }).tap();
  await page.getByRole('button', { name: '막힌 물길 도와주기', exact: true }).tap();
  const r = await page.locator('.coop-water .coop-scene').boundingBox();
  await touch('touchStart', r!.x + r!.width * .25, r!.y + r!.height * .4);
  await touch('touchMove', r!.x + r!.width * .75, r!.y + r!.height * .4); await touch('touchEnd');
  await expect(page.getByRole('button', { name: '물길 정비팀에 보내기' })).toBeEnabled();
  await page.getByRole('button', { name: '물길 정비팀에 보내기' }).tap();
  await expect(page.locator('.coop-result')).toBeVisible();
  await page.getByRole('button', { name: '다른 곳도 도와주기' }).tap();
  await page.getByRole('button', { name: '숲 옆 공사장 도와주기', exact: true }).tap();
  const slider = await page.getByRole('slider', { name: '공사 소리 줄이기' }).boundingBox();
  await touch('touchStart', slider!.x + slider!.width * .8, slider!.y + slider!.height / 2);
  await touch('touchMove', slider!.x + slider!.width * .2, slider!.y + slider!.height / 2); await touch('touchEnd');
  await expect(page.getByRole('button', { name: '공사팀에 약속 전하기' })).toBeEnabled();
  await page.getByRole('button', { name: '공사팀에 약속 전하기' }).tap();
  await expect(page.locator('.coop-result')).toBeVisible();
  await expect(page.locator('.coop-ending')).toHaveCount(0);
  await page.getByRole('button', { name: '함께 바꾼 숲 보기' }).tap();
  await expect(page.locator('.coop-ending')).toBeVisible();
  const compare = await page.locator('.coop-comparison__pictures').boundingBox();
  await touch('touchStart', compare!.x + compare!.width * .8, compare!.y + compare!.height / 2);
  await touch('touchMove', compare!.x + compare!.width * .2, compare!.y + compare!.height / 2); await touch('touchEnd');
  await expect(page.getByRole('slider', { name: '숲의 전후 모습 비교' })).toHaveValue('20');
  await context.close();
});

test('keyboard planting stays in order and cancelled or misplaced strokes do not complete a job', async ({ page }) => {
  await seed(page);
  await page.getByRole('button', { name: '함께 숲으로 가기' }).click();
  await page.getByRole('button', { name: '나무가 베인 곳 도와주기', exact: true }).click();
  const palette = page.getByRole('button', { name: '열매나무 묘목', exact: true });
  const start = await palette.boundingBox();
  await page.mouse.move(start!.x + 20, start!.y + 20); await page.mouse.down();
  await page.mouse.move(10, 10, { steps: 8 }); await page.mouse.up();
  await expect(page.locator('.coop-plant-site.is-planted')).toHaveCount(0);
  await palette.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: '1번 자리에 묘목 심기' })).toBeFocused();
  await page.keyboard.press('Enter'); await expect(palette).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: '2번 자리에 묘목 심기' })).toBeFocused();
  await page.keyboard.press('Space');
  await expect(page.getByRole('button', { name: '함께 나무 돌보기' })).toBeFocused();
  await page.keyboard.press('Enter'); await expect(page.locator('.coop-result')).toBeVisible();
  await page.getByRole('button', { name: '다른 곳도 도와주기' }).click();
  await page.getByRole('button', { name: '막힌 물길 도와주기', exact: true }).click();
  const scene = await page.locator('.coop-water .coop-scene').boundingBox();
  await page.mouse.move(scene!.x + scene!.width * .1, scene!.y + 20); await page.mouse.down();
  await page.mouse.move(scene!.x + scene!.width * .2, scene!.y + 20, { steps: 5 }); await page.mouse.up();
  await expect(page.getByRole('button', { name: '물길 정비팀에 보내기' })).toBeDisabled();
  await page.mouse.move(scene!.x + scene!.width * .3, scene!.y + scene!.height * .4); await page.mouse.down();
  await page.mouse.move(scene!.x + scene!.width * .7, scene!.y + scene!.height * .4, { steps: 5 });
  await page.keyboard.press('Escape'); await page.mouse.up();
  await expect(page.getByRole('button', { name: '물길 정비팀에 보내기' })).toBeDisabled();
  await page.getByRole('button', { name: '막힌 곳 표시하기' }).focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: '물길 정비팀에 보내기' })).toBeEnabled();
});

